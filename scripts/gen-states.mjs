// gen-states.mjs – writes src/states.js, DOOM's state table, from info.c and
// info.h, the weapons' states from d_items.c and the random table from m_random.c
// (Chocolate Doom's, the GPL-2 release of id's code). Run it again only to regenerate the file; it isn't
// part of the build.
//
//   node scripts/gen-states.mjs              (fetches the four files, at the tag below)
//   node scripts/gen-states.mjs DIR          (reads DIR/info.c, info.h, d_items.c and m_random.c)
//
// src/states.js is GPL-2.0-or-later, like its source; the rest of the repo is
// MIT (README, Licence). This script only reads the C and writes data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TAG = 'chocolate-doom-3.1.0';
const BASE = `https://raw.githubusercontent.com/chocolate-doom/chocolate-doom/${TAG}/src/doom`;

async function source(name) {
  const dir = process.argv[2];
  if (dir) return fs.readFileSync(path.join(dir, name), 'utf8');
  const r = await fetch(`${BASE}/${name}`);
  if (!r.ok) throw new Error(`${BASE}/${name}: ${r.status}`);
  return r.text();
}

const infoC = await source('info.c');
const infoH = await source('info.h');
const items = await source('d_items.c');
const random = await source('m_random.c');

// statenum_t, in order: S_NULL = 0 …
const enumBody = /typedef enum\s*\{([\s\S]*?)NUMSTATES\s*\}\s*statenum_t;/.exec(infoH)?.[1];
if (!enumBody) throw new Error('info.h: no statenum_t');
const stateNames = [...enumBody.matchAll(/\b(S_[A-Z0-9_]+)\b/g)].map((m) => m[1]);
const stateIndex = new Map(stateNames.map((n, i) => [n, i]));

// states[]: {SPR_POSS,0,10,{A_Look},S_POSS_STND2,0,0},	// S_POSS_STND
const rows = [...infoC.matchAll(/^\s*\{SPR_(\w+),(\d+),(-?\d+),\{(\w+)\},(S_\w+),(-?\d+),(-?\d+)\},?\s*\/\/\s*(S_\w+)/gm)];
if (rows.length !== stateNames.length) throw new Error(`info.c has ${rows.length} states, info.h names ${stateNames.length}`);
const states = rows.map((m, i) => {
  const [, sprite, frame, tics, action, next, misc1, misc2, name] = m;
  if (name !== stateNames[i]) throw new Error(`state ${i}: info.c says ${name}, info.h ${stateNames[i]}`);
  const f = Number(frame);
  return [name, sprite, String.fromCharCode(65 + (f & 0x7fff)), f & 0x8000 ? 1 : 0, Number(tics),
    action === 'NULL' ? null : action, stateIndex.get(next), Number(misc1), Number(misc2)];
});

// mobjinfo[]: each type's map number and its eight states
const FIELDS = ['spawnstate', 'seestate', 'painstate', 'meleestate', 'missilestate', 'deathstate', 'xdeathstate', 'raisestate'];
const mobj = {};
for (const m of infoC.matchAll(/\{\s*\/\/\s*(MT_\w+)([\s\S]*?)\n\s*\}/g)) {
  const [, mt, body] = m;
  const field = (f) => new RegExp(`\\n\\s*([^,\\n]+?),?\\s*\\/\\/\\s*${f}\\b`).exec(body)?.[1].trim();
  const st = (v) => (v === undefined || v === '0' ? 0 : stateIndex.get(v));
  mobj[mt] = { ednum: Number(field('doomednum')), states: FIELDS.map((f) => st(field(f))) };
  if (mobj[mt].states.some((s) => s === undefined)) throw new Error(`${mt}: a state info.h doesn't name`);
}

// sprnames[]: DeHackEd's sprite numbers (a Frame block's "Sprite number")
const sprBody = /sprnames\[\]\s*=\s*\{([\s\S]*?)\}/.exec(infoC)?.[1];
if (!sprBody) throw new Error('info.c: no sprnames[]');
const sprites = [...sprBody.matchAll(/"(\w{4})"/g)].map((m) => m[1]);

// rndtable[]: P_Random's and M_Random's 256 numbers
const rndBody = /rndtable\[256\]\s*=\s*\{([\s\S]*?)\}/.exec(random)?.[1];
if (!rndBody) throw new Error('m_random.c: no rndtable[]');
const rnd = [...rndBody.matchAll(/\d+/g)].map((m) => Number(m[0]));
if (rnd.length !== 256) throw new Error(`m_random.c: rndtable has ${rnd.length} numbers, not 256`);

// weaponinfo[]: each weapon's ammo and its five states (up, down, ready, attack, flash), in
// weapontype_t's order (wp_fist … wp_supershotgun)
const winfo = /weaponinfo\[NUMWEAPONS\]\s*=\s*\{([\s\S]*?)\n\};/.exec(items)?.[1];
if (!winfo) throw new Error('d_items.c: no weaponinfo[]');
const weapons = [...winfo.matchAll(/\{\s*\/\/\s*([^\n]+?)\s*\n\s*(am_\w+),\s*(S_\w+),\s*(S_\w+),\s*(S_\w+),\s*(S_\w+),\s*(S_\w+)\s*\}/g)]
  .map(([, name, ammo, ...st]) => {
    const ids = st.map((n) => stateIndex.get(n));
    if (ids.some((i) => i === undefined)) throw new Error(`weaponinfo ${name}: a state info.h doesn't name`);
    return { name, ammo: ammo.slice(3), states: ids };
  });
if (weapons.length !== 9) throw new Error(`d_items.c has ${weapons.length} weapons, not 9`);

const header = /^\/\/\s*Copyright[^\n]*(\n\/\/\s*Copyright[^\n]*)*/m.exec(infoC)[0].replace(/^\/\/\s*/gm, ' * ');
const out = `/*! @license GPL-2.0-or-later
 * states.js – DOOM's state table: info.c's states[] (each frame's sprite, frame
 * letter, full-bright bit, tics, action and next state) and the state columns
 * of mobjinfo[], its sprite names, d_items.c's weaponinfo[] and m_random.c's
 * rndtable[], as data. Generated by scripts/gen-states.mjs from Chocolate
 * Doom's info.c, info.h, d_items.c and m_random.c (${TAG}); don't edit it
 * by hand.
 *
${header}
 *
 * This program is free software; you can redistribute it and/or modify it
 * under the terms of the GNU General Public License as published by the Free
 * Software Foundation; either version 2 of the License, or (at your option)
 * any later version. It is distributed in the hope that it will be useful, but
 * WITHOUT ANY WARRANTY; without even the implied warranty of MERCHANTABILITY
 * or FITNESS FOR A PARTICULAR PURPOSE. See LICENSES/GPL-2.0.md.
 *
 * The rest of Firebird DOOM is MIT (LICENSE); a build that includes this file
 * is distributed under the GPL as a whole.
 */

/** [name, sprite, frame, bright, tics, action, next, misc1, misc2]; the index is DOOM's statenum */
export const STATES = [
${states.map((s) => `  ${JSON.stringify(s)},`).join('\n')}
];

/** rndtable[]: P_Random() returns rndtable[++prndindex & 255] (m_random.c) */
export const RNDTABLE = ${JSON.stringify(rnd)};

/** sprnames[], in spritenum_t's order: DeHackEd's sprite numbers */
export const SPRITES = ${JSON.stringify(sprites)};

/** the order of each MOBJINFO entry's states */
export const STATE_FIELDS = ${JSON.stringify(FIELDS)};

/** MT_ name → { ednum (the map's thing number, -1: none), states (statenums, STATE_FIELDS order; 0 = none) } */
export const MOBJINFO = {
${Object.entries(mobj).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join('\n')}
};

/** the order of each WEAPONINFO entry's states */
export const WEAPON_FIELDS = ["upstate","downstate","readystate","atkstate","flashstate"];

/** weaponinfo[], in weapontype_t's order (wp_fist = 0 … wp_supershotgun = 8): { name, ammo (clip, shell, cell, misl, noammo), states (statenums, WEAPON_FIELDS order) } */
export const WEAPONINFO = [
${weapons.map((w) => `  ${JSON.stringify(w)},`).join('\n')}
];
`;
fs.writeFileSync(path.join(root, 'src/states.js'), out);
console.log(`src/states.js: ${states.length} states, ${Object.keys(mobj).length} thing types, ${weapons.length} weapons, ${sprites.length} sprites, the random table`);
