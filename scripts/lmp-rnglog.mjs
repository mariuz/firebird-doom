// lmp-rnglog.mjs – who draws each random number: the port plays a fixture demo
// (scripts/fixtures/lmp/NAME.lmp) and, in tics FROM to TO, logs every P_Random draw with the
// index, whose turn it was (THINK_KEY: -1 the players, else a thing's key) and the call stack
// of procedures that drew it (MON$CALL_STACK, read in an autonomous transaction: a monitoring
// snapshot lasts a transaction, so the doom_tic's own would be stale). Set beside vanilla's
// trace (NAME.trace: the index after each tic), it shows which draw is extra or missing.
//
//   node scripts/lmp-rnglog.mjs e1m1-walk 119 119
//   node scripts/lmp-rnglog.mjs map01-attract 50 52 public/wads/freedoom2.wad
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { FirebirdBrowser, DirectTransport } from 'firebird-wasm/browser';
import { Wad } from '../src/wad.js';
import { createSchema, loadResources, loadMap } from '../src/loader.js';
import { parseLmp, portCmd } from '../src/lmp.js';
import { startDemo } from './lmp-sync.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [name, from, to, wadArg] = process.argv.slice(2);
if (!name || !from || !to) {
  console.log('usage: node scripts/lmp-rnglog.mjs NAME FROM TO [WAD]');
  process.exit(1);
}
const wadPath = wadArg ?? path.join(root, 'public/wads', name.startsWith('map') ? 'freedoom2.wad' : 'freedoom1.wad');
const sql = Object.fromEntries(['schema', 'game', 'render'].map((n) => [n, fs.readFileSync(path.join(root, `sql/${n}.sql`), 'utf8')]));
const db = new FirebirdBrowser('memory://rnglog', { transport: new DirectTransport({ threads: false }) });
await createSchema(db, sql);
const wad = new Wad(fs.readFileSync(wadPath));
const res = await loadResources(db, wad);
const demo = parseLmp(fs.readFileSync(path.join(root, 'scripts/fixtures/lmp', `${name}.lmp`)));
await startDemo(db, wad, res, demo, loadMap);
await db.exec('CREATE TABLE rnglog (n INTEGER GENERATED BY DEFAULT AS IDENTITY, tic INTEGER, i INTEGER, k VARCHAR(30), stack VARCHAR(2000))');
for (let t = 0; t < Number(to) && t < demo.tics.length; t++) {
  if (t + 1 === Number(from)) {
    // P_Random, logging each draw
    await db.query(`CREATE OR ALTER FUNCTION p_rand256 RETURNS INTEGER AS
      DECLARE i INTEGER;
      DECLARE cs VARCHAR(2000);
      BEGIN
        IN AUTONOMOUS TRANSACTION DO
          SELECT LIST(TRIM(c.MON$OBJECT_NAME), '<') FROM MON$CALL_STACK c
            JOIN MON$STATEMENTS s ON s.MON$STATEMENT_ID = c.MON$STATEMENT_ID
           WHERE s.MON$ATTACHMENT_ID = CURRENT_CONNECTION INTO cs;
        UPDATE game g SET rng = MOD(g.rng + 1, 256) WHERE g.id = 1 RETURNING g.rng INTO i;
        INSERT INTO rnglog (tic, i, k, stack) VALUES ((SELECT g.tic FROM game g WHERE g.id = 1), :i,
          RDB$GET_CONTEXT('USER_TRANSACTION', 'THINK_KEY'), :cs);
        RETURN (SELECT r.v FROM rndtable r WHERE r.i = :i);
      END`);
  }
  await db.query('SELECT * FROM doom_tic(1, ?, ?, ?, ?, ?, ?, ?)', portCmd(demo.tics[t][demo.consoleplayer] ?? demo.tics[t][0]));
}
const { rows } = await db.query(`SELECT l.tic, l.i, l.k, l.stack,
    (SELECT t.kind || ' ' || t.thing_type FROM things t WHERE COALESCE(t.think_key, 2 * t.id) = CAST(l.k AS BIGINT)) th
    FROM rnglog l ORDER BY l.n`);
for (const r of rows) console.log(`tic ${r.TIC}  #${r.I}  turn ${r.K}${r.TH ? ` (${r.TH})` : ''}  ${r.STACK}`);
await db.close();
